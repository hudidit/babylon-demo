"""Two short CC0 gull phrases; silence and timing belong to the controller, never a loop."""
from pathlib import Path
import importlib.util
import json
import tempfile
from array import array

ROOT=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('soundscape',ROOT/'tools/prepare-soundscape-audio.py')
soundscape=importlib.util.module_from_spec(spec);spec.loader.exec_module(soundscape)
audio=soundscape.audio
SOURCE,OUTPUT=ROOT/'assets/audio-source/birds',ROOT/'public/audio/birds'

def main():
    sources=json.loads((SOURCE/'source.json').read_text())['sources'];source=sources[0]
    path=SOURCE/source['file'];assert audio.digest(path.read_bytes())==source['sha256']
    OUTPUT.mkdir(parents=True,exist_ok=True);rows=[];catalog=[]
    with tempfile.TemporaryDirectory(prefix='babylon-birds-') as temp:
        channels=audio.read_pcm(path,Path(temp));mono=[sum(v)/len(channels) for v in zip(*channels)]
        for i,start in enumerate([3.45,8.70],1):
            values=mono[round(start*audio.RATE):round((start+.65)*audio.RATE)]
            # Soften nearby high-frequency edges; do not normalize the whole outdoor scene upwards.
            values=soundscape.lowpass(values,4500)
            data=audio.wav_bytes(soundscape.finish([values],.30));pcm=array('h',data[44:]);digest=audio.digest(data)
            clip_id='bird-call-'+str(i);name=clip_id+'.'+digest[:10]+'.wav';(OUTPUT/name).write_bytes(data)
            rows.append(dict(id=clip_id,file='audio/birds/'+name,sourceId='gulls',sourceSha256=source['sha256'],license='CC0-1.0',
                bytes=len(data),sha256=digest,sampleRate=audio.RATE,channels=1,bitDepth=16,frames=len(pcm),durationSeconds=len(pcm)/audio.RATE,
                decodedBytes=len(pcm)*4,peak=max(abs(v) for v in pcm)/32768,loop=False,
                processing=dict(start=start,inputDuration=.65,lowPassHz=4500,removeDC=True,fadeIn=.003,fadeOut=.015,peakTarget=.30)))
            catalog.append(dict(id=clip_id,cue='bird-call',file='audio/birds/'+name,priority=0,gain=.045,preload='variation',group='ambience'))
    manifest=dict(schemaVersion=1,generator='tools/prepare-bird-audio.py',generatorSha256=audio.digest(Path(__file__).read_bytes()),
        sources=[{k:v for k,v in source.items() if k!='file'}],files=rows,totalBytes=sum(r['bytes'] for r in rows),decodedBytes=sum(r['decodedBytes'] for r in rows))
    (OUTPUT/'source.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
    used={Path(r['file']).name for r in rows}
    for p in OUTPUT.glob('*.wav'):
        if p.name not in used:p.unlink()
    (ROOT/'src/examples/RoomBirdAudioCatalog.ts').write_text('// Generated by tools/prepare-bird-audio.py; provenance: public/audio/birds/source.json.\n'
        'import type { AudioClip } from "./RoomAudioCatalog";\nexport const BIRD_AUDIO_CLIPS: readonly AudioClip[] = [\n'+''.join('  '+json.dumps(row)+',\n' for row in catalog)+'];\n')
    print(json.dumps(dict(files=len(rows),bytes=manifest['totalBytes'],decodedBytes=manifest['decodedBytes'])))

if __name__=='__main__':main()
